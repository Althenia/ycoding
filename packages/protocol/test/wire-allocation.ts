export function messageTags(
  name: string,
  fields: readonly { readonly name: string; readonly tag?: number }[],
  allocation: WireAllocation = wireAllocation,
) {
  const preset = fields.flatMap((field) => (field.tag === undefined ? [] : [field.tag]))
  if (!preset.length) return slots("field", name, names(fields), entryOf(allocation.messages, name))
  if (preset.length !== fields.length) throw new Error(`${name}: preset tags must cover every field`)
  if (new Set(preset).size !== preset.length) throw new Error(`${name}: duplicate preset tag`)
  return preset
}

export function enumNumbers(name: string, values: readonly Literal[], allocation: WireAllocation = wireAllocation) {
  return slots("literal", name, values, entryOf(allocation.enums, name))
}

export function unionSlots(
  name: string,
  identities: readonly (string | undefined)[],
  allocation: WireAllocation = wireAllocation,
) {
  const entry = entryOf(allocation.messages, name)
  if (!entry) return undefined
  const keys = identities.flatMap((identity) => (identity === undefined ? [] : [identity]))
  if (keys.length !== identities.length) throw new Error(`member has no stable identity in union ${name}`)
  return slots("member", name, keys, entry)
}

export function reservedLine(kind: "message" | "enum", name: string, allocation: WireAllocation = wireAllocation) {
  const numbers = (entryOf(kind === "message" ? allocation.messages : allocation.enums, name) ?? []).flatMap(
    (item, index) => (isReserved(item) ? [index + 1] : []),
  )
  return numbers.length ? `  reserved ${numbers.join(", ")};\n` : ""
}

function slots<T extends Literal>(
  kind: string,
  name: string,
  live: readonly T[],
  entry: readonly (T | Reserved)[] | undefined,
) {
  if (!entry) return live.map((_, index) => index + 1)
  const allocated = new Map<T, number>()
  const retired = new Set<string>()
  entry.forEach((item, index) => {
    if (isReserved(item)) {
      if (retired.has(item.reserved)) throw new Error(`duplicate allocation ${name}: ${item.reserved}`)
      retired.add(item.reserved)
      return
    }
    if (allocated.has(item)) throw new Error(`duplicate allocation ${name}: ${String(item)}`)
    allocated.set(item, index + 1)
  })
  allocated.forEach((_, item) => {
    if (retired.has(String(item))) throw new Error(`duplicate allocation ${name}: ${String(item)}`)
  })
  const declared = new Set(live)
  allocated.forEach((_, item) => {
    if (!declared.has(item))
      throw new Error(`stale allocation ${name}: ${String(item)} is neither declared nor reserved`)
  })
  return live.map((item) => {
    const slot = allocated.get(item)
    if (slot === undefined) throw new Error(`unallocated ${kind} ${name}: ${String(item)}`)
    return slot
  })
}

const names = (fields: readonly { readonly name: string }[]) => fields.map((field) => field.name)

function entryOf<T>(table: Readonly<Record<string, T>>, name: string) {
  return Object.hasOwn(table, name) ? table[name] : undefined
}

function isReserved(item: Literal | Reserved): item is Reserved {
  return typeof item === "object"
}
