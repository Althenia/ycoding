  await expect(run(boundary(wrongManifest, events, { tauri: async () => { wrongManifest.file(`${APP}/Contents/Resources/backend.json`, "other"); return 0 } }))).rejects.toThrow("not the one just prepared")
  expect(events).not.toContain(`copy:${OUT}/YCoding Desktop.app`)

  const twoExecutables = seeded()
  await expect(run(boundary(twoExecutables, [], { tauri: async () => { twoExecutables.file(`${APP}/Contents/MacOS/extra`, "x", 0o755); return 0 } }))).rejects.toThrow("exactly one main executable")

  const changedPrepared = seeded()
  await expect(run(boundary(changedPrepared, [], { tauri: async () => { changedPrepared.file(`${WORKSPACE}/runtime/backend.json`, "rewritten"); return 0 } }))).rejects.toThrow("changed during the Tauri build")

  const badCopy = seeded()
  await expect(run(boundary(badCopy, [], {
    copy: async (from, to) => {
      await badCopy.copy(from, to)
      if (to === `${OUT}/YCoding Desktop.app`) badCopy.file(`${to}/Contents/Resources/backend.json`, "tampered")
    },
  }))).rejects.toThrow("copied application differs")

