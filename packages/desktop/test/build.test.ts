type Node = { kind: Kind; mode: number; content: string; target: string }

function memory() {
  const nodes = new Map<string, Node>()
  const set = (target: string, kind: Kind, mode: number, content = "", link = "") => { nodes.set(target, { kind, mode, content, target: link }) }
  const files: Files = {
    info: async (target) => { const node = nodes.get(target); return node ? { kind: node.kind, mode: node.mode, size: node.content.length } : undefined },
    list: async (target) => [...nodes.keys()].filter((key) => key !== target && path.dirname(key) === target).map((key) => path.basename(key)),
    link: async (target) => { const node = nodes.get(target); if (node?.kind !== "symlink") throw new Error("Not a link."); return node.target },
    digest: async (target) => createHash("sha256").update(nodes.get(target)?.content ?? "").digest("hex"),
    real: async (target) => { if (!nodes.has(target)) throw new Error("ENOENT"); return target },
    text: async (target) => { const node = nodes.get(target); if (node?.kind !== "file") throw new Error("ENOENT"); return node.content },
  }
  return {
    nodes,
    files,
    dir: (target: string, mode = 0o755) => set(target, "dir", mode),
    file: (target: string, content: string, mode = 0o644) => set(target, "file", mode, content),
    link: (target: string, destination: string) => set(target, "symlink", 0, "", destination),
    other: (target: string) => set(target, "other", 0o600),
    copy: async (from: string, to: string) => {
      for (const [key, node] of [...nodes]) if (key === from || key.startsWith(`${from}/`)) nodes.set(to + key.slice(from.length), { ...node })
    },
  }
}

