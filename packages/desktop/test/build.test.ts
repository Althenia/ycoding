test("fingerprints and compares absent, changed, extra, missing, type, mode and link differences", async () => {
  const left = memory()
  left.dir("/a")
  left.file("/a/f", "one")
  left.link("/a/l", "f")
  const build = async (change: (fake: ReturnType<typeof memory>) => void) => {
    const right = memory()
    right.dir("/a")
    right.file("/a/f", "one")
    right.link("/a/l", "f")
    change(right)
    return difference(await fingerprint(left.files, "/a"), await fingerprint(right.files, "/a"))
  }
  expect(await build(() => undefined)).toBeUndefined()
  expect(await build((fake) => fake.file("/a/f", "two"))).toContain("changed entry f")
  expect(await build((fake) => fake.file("/a/g", "x"))).toContain("extra entry g")
  expect(await build((fake) => fake.nodes.delete("/a/f"))).toContain("missing entry f")
  expect(await build((fake) => fake.file("/a/f", "one", 0o755))).toContain("changed entry f")
  expect(await build((fake) => { fake.nodes.delete("/a/l"); fake.file("/a/l", "f") })).toContain("changed entry l")
  expect(await build((fake) => fake.link("/a/l", "elsewhere"))).toContain("changed entry l")
  expect(difference(await fingerprint(left.files, "/missing"), await fingerprint(left.files, "/a"))).toContain("status")
  expect((await fingerprint(left.files, "/missing")).status).toBe("absent")
  const special = memory()
  special.dir("/a")
  special.other("/a/socket")
  await expect(fingerprint(special.files, "/a")).rejects.toThrow("special")
  const linkedRoot = memory()
  linkedRoot.link("/a", "/elsewhere")
  await expect(fingerprint(linkedRoot.files, "/a")).rejects.toThrow("regular file or directory")
})

