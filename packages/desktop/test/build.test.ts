function boundary(fake: ReturnType<typeof memory>, events: string[], overrides: Partial<Boundary> = {}): Boundary {
  return {
    files: fake.files,
    assertSigning: async () => { events.push("signing") },
    metadata: async () => { events.push("metadata"); return { target: TARGET, workspace: WORKSPACE } },
    lock: async (file, token) => { events.push(`lock:${file}:${token}`) },
    unlock: async (file, token) => { events.push(`unlock:${file}:${token}`) },
    mkdir: async (target) => { events.push(`mkdir:${target}`); fake.dir(target) },
    mkdirs: async (target) => { events.push(`mkdirs:${target}`); fake.dir(target) },
    copy: async (from, to) => { events.push(`copy:${to}`); await fake.copy(from, to) },
    write: async (target, text) => { events.push(`write:${target}`); fake.file(target, text) },
    prepare: async (output) => { events.push(`prepare:${output}`); return { version: "0.0.0" } },
    tauri: async (command) => { events.push(`tauri:${command.join(" ")}`); return 0 },
    ...overrides,
  }
}

