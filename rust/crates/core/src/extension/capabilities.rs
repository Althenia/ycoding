    #[test]
    fn interaction_has_a_disableable_builtin_tool_capability() {
        assert!(super::PRE.contains(&"ycoding.tool.interaction"));
        assert!(super::DISABLEABLE.contains(&"ycoding.tool.interaction"));
        assert_eq!(
            super::tool_name("ycoding.tool.interaction"),
            Some("interaction")
        );
    }
